// Generates src/theme/tokens.generated.ts from the web design tokens so the two
// clients cannot drift apart. React Native cannot parse oklch(), so each colour
// is converted to sRGB (hex, or rgba() when it carries an alpha channel).
//
//   pnpm --filter @schoolhub/mobile tokens
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const cssPath = resolve(here, "../../web/src/index.css");
const outPath = resolve(here, "../src/theme/tokens.generated.ts");

// Semantic tokens that mobile uses. Sidebar and support aliases are web-only.
const KEEP = [
  "background", "foreground", "card", "card-foreground", "popover", "popover-foreground",
  "primary", "primary-foreground", "secondary", "secondary-foreground", "accent", "accent-foreground",
  "muted", "muted-foreground", "border", "input", "ring", "overlay",
  "destructive", "destructive-foreground", "success", "success-foreground",
  "warning", "warning-foreground", "info", "info-foreground", "highlight", "highlight-foreground",
  "brand", "brand-mid", "brand-soft", "brand-accent", "brand-glow", "brand-foreground",
  "chart-1", "chart-2", "chart-3", "chart-4", "chart-5",
];

const css = readFileSync(cssPath, "utf8");

function block(selector) {
  const start = css.search(new RegExp(`^${selector.replace(".", "\\.")}\\s*\\{`, "m"));
  if (start < 0) throw new Error(`Block ${selector} not found in index.css`);
  const open = css.indexOf("{", start);
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css[i] === "{") depth++;
    if (css[i] === "}" && --depth === 0) return css.slice(open + 1, i);
  }
  throw new Error(`Unterminated block ${selector}`);
}

function vars(body) {
  const out = {};
  for (const m of body.matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/g)) out[m[1]] = m[2].trim();
  return out;
}

const clamp01 = (x) => Math.min(1, Math.max(0, x));
const gamma = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * Math.pow(c, 1 / 2.4) - 0.055);
const hex2 = (x) => Math.round(clamp01(x) * 255).toString(16).padStart(2, "0");

function oklchToRgb(L, C, hDeg) {
  const h = (hDeg * Math.PI) / 180;
  const a = C * Math.cos(h);
  const b = C * Math.sin(h);
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.291485548 * b;
  const l = l_ ** 3, m = m_ ** 3, s = s_ ** 3;
  return [
    gamma(+4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s),
    gamma(-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s),
    gamma(-0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s),
  ];
}

function toColor(value) {
  const m = value.match(/^oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+))?\s*\)$/);
  if (!m) throw new Error(`Unsupported colour value: ${value}`);
  const [, L, C, H, A] = m;
  const [r, g, b] = oklchToRgb(+L, +C, +H);
  if (A !== undefined && +A < 1) {
    return `rgba(${Math.round(clamp01(r) * 255)}, ${Math.round(clamp01(g) * 255)}, ${Math.round(clamp01(b) * 255)}, ${+A})`;
  }
  return `#${hex2(r)}${hex2(g)}${hex2(b)}`;
}

const camel = (k) => k.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const light = vars(block(":root"));
const dark = { ...light, ...vars(block(".dark")) };

function build(source) {
  const lines = [];
  for (const key of KEEP) {
    if (!(key in source)) throw new Error(`Token --${key} missing from index.css`);
    lines.push(`  ${camel(key)}: ${JSON.stringify(toColor(source[key]))},`);
  }
  return lines.join("\n");
}

const file = `// AUTO-GENERATED by scripts/generate-tokens.mjs from apps/web/src/index.css.
// Do not edit by hand. Run \`pnpm --filter @schoolhub/mobile tokens\`.

export const lightTokens = {
${build(light)}
} as const;

export const darkTokens = {
${build(dark)}
} as const;

export type ColorTokens = { [K in keyof typeof lightTokens]: string };
`;

writeFileSync(outPath, file);
console.log(`Wrote ${outPath} (${KEEP.length} tokens x 2 themes)`);
