import ExcelJS from "exceljs";
import { describe, expect, it } from "vitest";
import { buildFinanceWorkbook } from "./finance-exports.helpers.js";

describe("finance export workbook", () => {
  it("writes numeric money cells, formula totals, formats and report metadata", async () => {
    const buffer = await buildFinanceWorkbook({
      title: "Payment register",
      headers: ["Receipt", "Amount (GHS)", "Date"],
      rows: [
        ["RCT-001", 10.25, new Date("2026-10-01T00:00:00.000Z")],
        ["RCT-002", 20.5, new Date("2026-10-02T00:00:00.000Z")],
      ],
      columnTypes: ["text", "money", "date"],
      totalColumns: [1],
      totalLabel: "Totals",
      reportInfo: { School: "Test School", Period: "2026-10", "Generated by": "Test Accountant" },
    });

    const workbook = new ExcelJS.Workbook();
    await workbook.xlsx.load(Uint8Array.from(buffer).buffer as ArrayBuffer);
    const sheet = workbook.getWorksheet("Payment register");
    expect(sheet).toBeDefined();
    expect(sheet!.views[0]).toMatchObject({ state: "frozen", ySplit: 1 });
    expect(sheet!.getCell("B2").type).toBe(ExcelJS.ValueType.Number);
    expect(sheet!.getCell("B3").type).toBe(ExcelJS.ValueType.Number);
    expect(sheet!.getCell("B2").value).toBe(10.25);
    expect(sheet!.getCell("B2").numFmt).toContain("#,##0.00");
    expect(sheet!.getCell("C2").value).toBeInstanceOf(Date);
    expect(sheet!.getCell("B4").value).toMatchObject({ formula: "SUM(B2:B3)" });
    expect(sheet!.getCell("A4").value).toBe("Totals");

    const reportInfo = workbook.getWorksheet("Report info");
    expect(reportInfo).toBeDefined();
    expect(reportInfo!.getCell("A2").value).toBe("School");
    expect(reportInfo!.getCell("B2").value).toBe("Test School");
    expect(reportInfo!.getCell("B4").value).toBe("Test Accountant");
  });

  it("keeps user-controlled strings as literal text", async () => {
    const buffer = await buildFinanceWorkbook({
      title: "Audit export",
      headers: ["Description", "Amount"],
      rows: [['=HYPERLINK("https://example.test")', 12]],
      columnTypes: ["text", "number"],
      reportInfo: { School: "Test School" },
    });
    const workbook = new ExcelJS.Workbook();
    await workbook.xlsx.load(buffer);
    expect(workbook.getWorksheet("Audit export")!.getCell("A2").value).toBe(`\'=HYPERLINK("https://example.test")`);
  });

  it("produces a non-circular zero total for an empty report", async () => {
    const buffer = await buildFinanceWorkbook({
      title: "Empty report",
      headers: ["Label", "Amount (GHS)"],
      rows: [],
      columnTypes: ["text", "money"],
      totalColumns: [1],
      reportInfo: { School: "Test School" },
    });
    const workbook = new ExcelJS.Workbook();
    await workbook.xlsx.load(buffer);
    expect(workbook.getWorksheet("Empty report")!.getCell("B2").value).toBe(0);
  });
});
