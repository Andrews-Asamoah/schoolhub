import ExcelJS from "exceljs";

export type FinanceExportColumnType = "text" | "number" | "money" | "date";
export type FinanceExportCell = string | number | Date | null;

export interface FinanceWorkbookInput {
  title: string;
  headers: string[];
  rows: FinanceExportCell[][];
  columnTypes: FinanceExportColumnType[];
  /** Zero-based columns whose total cells should use SUM formulas. */
  totalColumns?: number[];
  totalLabel?: string;
  reportInfo: Record<string, string>;
}

function excelText(value: FinanceExportCell): string | number | Date {
  if (value == null) return "";
  if (value instanceof Date) return value;
  const text = String(value);
  return /^[\s]*[=+\-@\t\r]/.test(text) ? "'" + text : text;
}

function excelColumnName(index: number): string {
  let value = index + 1;
  let result = "";
  while (value > 0) {
    const part = (value - 1) % 26;
    result = String.fromCharCode(65 + part) + result;
    value = Math.floor((value - 1) / 26);
  }
  return result;
}

/** Creates an in-memory workbook; number and money cells remain numeric. */
export async function buildFinanceWorkbook(input: FinanceWorkbookInput): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = input.reportInfo["Generated by"] ?? "SchoolHub";
  workbook.created = new Date();
  const sheet = workbook.addWorksheet(input.title.slice(0, 31).replace(/[\\/?*[\]:]/g, " ") || "Report", {
    views: [{ state: "frozen", ySplit: 1 }],
  });

  sheet.addRow(input.headers);
  sheet.getRow(1).font = { bold: true, color: { argb: "FFFFFFFF" } };
  sheet.getRow(1).fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF334155" } };

  for (const row of input.rows) {
    sheet.addRow(row.map((value, index) => {
      const type = input.columnTypes[index] ?? "text";
      if (type === "text") return excelText(value);
      if (value == null || value === "") return "";
      if (type === "date") {
        if (value instanceof Date) return value;
        const date = new Date(String(value));
        return Number.isNaN(date.getTime()) ? excelText(value) : date;
      }
      if (typeof value === "number") return Number.isFinite(value) ? value : "";
      return excelText(value);
    }));
  }

  if (input.totalColumns?.length) {
    const totalRowIndex = sheet.rowCount + 1;
    const totalValues = input.headers.map((_, index) => {
      if (index === 0) return input.totalLabel ?? "Total";
      if (!input.totalColumns?.includes(index)) return "";
      if (input.rows.length === 0) return 0;
      const column = excelColumnName(index);
      return { formula: "SUM(" + column + "2:" + column + (totalRowIndex - 1) + ")" };
    });
    const totalRow = sheet.addRow(totalValues);
    totalRow.font = { bold: true };
    totalRow.border = { top: { style: "thin", color: { argb: "FF64748B" } } };
  }

  sheet.columns.forEach((column, index) => {
    const longest = Math.max(
      input.headers[index]?.length ?? 0,
      ...input.rows.map((row) => String(row[index] ?? "").length),
    );
    column.width = Math.min(Math.max(longest + 2, 10), 42);
    const type = input.columnTypes[index] ?? "text";
    if (type === "money") column.numFmt = '#,##0.00;[Red](#,##0.00)';
    else if (type === "number") column.numFmt = "#,##0.##";
    else if (type === "date") column.numFmt = "yyyy-mm-dd";
  });

  const info = workbook.addWorksheet("Report info");
  info.addRows([["Field", "Value"], ...Object.entries(input.reportInfo)]);
  info.getRow(1).font = { bold: true };
  info.columns = [{ width: 24 }, { width: 60 }];
  info.views = [{ state: "frozen", ySplit: 1 }];

  const result = await workbook.xlsx.writeBuffer();
  return Buffer.from(result);
}
